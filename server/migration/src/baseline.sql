CREATE MATERIALIZED VIEW learn_language.card_view AS
 SELECT c.id,
    c.source_id,
    c.source_page_number,
    c.data,
    c.readiness,
    c.due,
    c.reps,
    c.lapses,
    c.stability,
    c.state,
    c.last_review,
    c.flagged,
    c.type,
    rs.review_score,
    cs.correct_streak,
        CASE
            WHEN (((c.readiness)::text = ANY ((ARRAY['READY'::character varying, 'REVIEWED'::character varying, 'KNOWN'::character varying])::text[])) AND ((((c.type)::text <> ALL ((ARRAY['GRAMMAR'::character varying, 'SIMPLE'::character varying])::text[])) AND ((((c.data -> 'translation'::text) ->> 'en'::text) IS NULL) OR (TRIM(BOTH FROM ((c.data -> 'translation'::text) ->> 'en'::text)) = ''::text))) OR (((c.type)::text <> ALL ((ARRAY['GRAMMAR'::character varying, 'SIMPLE'::character varying])::text[])) AND ((((c.data -> 'translation'::text) ->> 'hu'::text) IS NULL) OR (TRIM(BOTH FROM ((c.data -> 'translation'::text) ->> 'hu'::text)) = ''::text))) OR (((c.type)::text <> ALL ((ARRAY['GRAMMAR'::character varying, 'SIMPLE'::character varying])::text[])) AND ((((c.data -> 'translation'::text) ->> 'ch'::text) IS NULL) OR (TRIM(BOTH FROM ((c.data -> 'translation'::text) ->> 'ch'::text)) = ''::text))) OR (((c.type)::text = 'VOCABULARY'::text) AND ((c.data ->> 'type'::text) = 'NOUN'::text) AND (((c.data ->> 'gender'::text) IS NULL) OR (TRIM(BOTH FROM (c.data ->> 'gender'::text)) = ''::text))) OR (((c.type)::text = 'VOCABULARY'::text) AND (((c.data ->> 'type'::text) IS NULL) OR (TRIM(BOTH FROM (c.data ->> 'type'::text)) = ''::text))) OR (((c.type)::text = 'GRAMMAR'::text) AND (((((c.data -> 'examples'::text) -> 0) ->> 'hu'::text) IS NULL) OR (TRIM(BOTH FROM (((c.data -> 'examples'::text) -> 0) ->> 'hu'::text)) = ''::text))) OR (((c.type)::text = 'SIMPLE'::text) AND (((c.data ->> 'frontText'::text) IS NULL) OR (TRIM(BOTH FROM (c.data ->> 'frontText'::text)) = ''::text) OR ((c.data ->> 'backText'::text) IS NULL) OR (TRIM(BOTH FROM (c.data ->> 'backText'::text)) = ''::text))))) THEN true
            ELSE false
        END AS is_unhealthy,
        CASE
            WHEN (((c.readiness)::text = 'READY'::text) AND ((c.state)::text = 'REVIEW'::text) AND (c.stability >= (30)::double precision) AND (c.reps >= 5) AND (c.lapses <= 1)) THEN true
            ELSE false
        END AS is_suggested_known
   FROM ((learn_language.cards c
     LEFT JOIN LATERAL ( SELECT (COALESCE((min(ranked.rn) FILTER (WHERE (ranked.rating < 3)) - 1), max(ranked.rn)))::integer AS correct_streak
           FROM ( SELECT review_logs.rating,
                    row_number() OVER (ORDER BY review_logs.review DESC) AS rn
                   FROM learn_language.review_logs
                  WHERE ((review_logs.card_id)::text = (c.id)::text)) ranked) cs ON (true))
     LEFT JOIN LATERAL ( SELECT
                CASE
                    WHEN (stats.total_count = 0) THEN NULL::integer
                    WHEN (stats.total_count = 1) THEN ((stats.last_review_success * (100)::numeric))::integer
                    ELSE (round((((0.5 * stats.last_review_success) + (0.5 * stats.prev_success_rate)) * (100)::numeric)))::integer
                END AS review_score
           FROM ( SELECT count(*) AS total_count,
                        CASE
                            WHEN (( SELECT review_logs_1.rating
                               FROM learn_language.review_logs review_logs_1
                              WHERE ((review_logs_1.card_id)::text = (c.id)::text)
                              ORDER BY review_logs_1.review DESC
                             LIMIT 1) >= 3) THEN 1.0
                            ELSE 0.0
                        END AS last_review_success,
                    COALESCE(( SELECT avg(
                                CASE
                                    WHEN (prev.rating >= 3) THEN 1.0
                                    ELSE 0.0
                                END) AS avg
                           FROM ( SELECT review_logs_1.rating
                                   FROM learn_language.review_logs review_logs_1
                                  WHERE ((review_logs_1.card_id)::text = (c.id)::text)
                                  ORDER BY review_logs_1.review DESC
                                 OFFSET 1) prev), 0.0) AS prev_success_rate
                   FROM learn_language.review_logs
                  WHERE ((review_logs.card_id)::text = (c.id)::text)) stats) rs ON (true))
  WITH NO DATA;

